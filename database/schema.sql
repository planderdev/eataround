create table journals (
  id bigint generated by default as identity primary key,
  slug varchar(120) not null unique,
  title varchar(190) not null,
  category varchar(80),
  excerpt varchar(500),
  content text,
  image_url varchar(500),
  is_visible smallint not null default 1,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table inquiries (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete set null,
  inquiry_type text not null default 'general' check (inquiry_type in ('product', 'event', 'package', 'general')),
  title varchar(190) not null,
  body text not null,
  status text not null default 'open' check (status in ('open', 'answered', 'closed')),
  created_at timestamptz not null default now()
);

create table product_detail_items (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  -- highlight/included/notice/recommended/excluded: body만 사용
  -- schedule: label=시간, body=내용 / point: label=제목, body=설명
  -- course: label=제목, body=설명, meta=소요시간, note=요약 / faq: label=질문, body=답변
  content_type text not null check (content_type in
    ('recommended', 'excluded', 'schedule', 'highlight', 'included', 'notice', 'point', 'course', 'faq')),
  label varchar(160),
  body varchar(500) not null,
  meta varchar(80),
  note varchar(200),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table product_reviews (
  id bigint generated by default as identity primary key,
  product_id bigint references products(id) on delete set null,
  user_id bigint references users(id) on delete set null,
  rating smallint not null default 5 check (rating between 1 and 5),
  body text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table coupons (
  id bigint generated by default as identity primary key,
  code varchar(80) not null unique,
  title varchar(190) not null,
  discount_type text not null default 'percent' check (discount_type in ('percent', 'amount')),
  discount_value integer not null,
  starts_at timestamptz,
  ends_at timestamptz,
  is_active smallint not null default 1,
  created_at timestamptz not null default now()
);

create table host_settlements (
  id bigint generated by default as identity primary key,
  host_name varchar(160) not null,
  sales_amount integer not null default 0,
  commission_amount integer not null default 0,
  payout_amount integer not null default 0,
  status text not null default 'draft' check (status in ('draft', 'confirmed', 'paid')),
  settled_at timestamptz,
  created_at timestamptz not null default now()
);

-- 조회·조인에 쓰는 인덱스 (외래키 포함)
