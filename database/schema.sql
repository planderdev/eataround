-- 이더라운드 Supabase(Postgres) 스키마
-- 서버(API Route)는 DATABASE_URL로 직접 접속하므로 RLS를 우회한다.
-- 모든 테이블에 RLS를 켜고 정책을 두지 않아, 공개 API 키(anon)로는 읽기·쓰기가 되지 않게 한다.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table users (
  id bigint generated by default as identity primary key,
  member_type text not null default 'personal' check (member_type in ('personal', 'company')),
  email varchar(190) not null unique,
  password_hash varchar(255) not null,
  name varchar(80) not null,
  phone varchar(40),
  organization_name varchar(160),
  business_number varchar(40),
  company_approved smallint not null default 0,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table products (
  id bigint generated by default as identity primary key,
  slug varchar(120) not null unique,
  title varchar(190) not null,
  summary varchar(500),
  description text,
  region varchar(80) not null,
  category varchar(80) not null,
  price integer not null default 0 check (price >= 0),
  original_price integer check (original_price >= 0),
  duration varchar(80),
  badge varchar(40),
  image_url varchar(500),
  host_name varchar(160),
  host_description varchar(500),
  place_name varchar(160),
  place_address varchar(300),
  eyebrow varchar(80),
  rating numeric(2, 1) check (rating between 0 and 5),
  review_count integer not null default 0 check (review_count >= 0),
  kicker varchar(160),
  group_label varchar(80),
  booking_deadline varchar(80),
  course_intro varchar(300),
  is_featured smallint not null default 0,
  is_visible smallint not null default 1,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table product_tags (
  product_id bigint not null references products(id) on delete cascade,
  tag varchar(60) not null,
  primary key (product_id, tag)
);

create table categories (
  id bigint generated by default as identity primary key,
  label varchar(80) not null unique,
  href varchar(300) not null,
  icon_asset varchar(300),
  tone text not null default 'green' check (tone in ('green', 'coral', 'blue', 'yellow', 'red', 'ink')),
  is_visible smallint not null default 1,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table product_schedules (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  schedule_date date not null,
  schedule_label varchar(80) not null,
  capacity integer not null check (capacity >= 0),
  booked integer not null default 0 check (booked >= 0),
  max_teams integer not null default 1,
  reserved_teams integer not null default 0,
  team_capacity integer not null default 1,
  reservation_type text not null default 'approval' check (reservation_type in ('instant', 'approval', 'inquiry')),
  approval_required smallint not null default 1,
  price integer not null check (price >= 0),
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now(),
  unique (product_id, schedule_date, schedule_label)
);

create table reservations (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete set null,
  product_id bigint references products(id) on delete set null,
  product_slug varchar(120),
  schedule_id bigint references product_schedules(id) on delete set null,
  schedule_date date,
  schedule_label varchar(80),
  people integer not null default 1,
  total_amount integer not null default 0,
  reservation_type text not null default 'approval' check (reservation_type in ('instant', 'approval', 'inquiry')),
  approval_required smallint not null default 1,
  status text not null default 'requested' check (status in ('requested', 'confirmed', 'paid', 'canceled')),
  memo varchar(500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table events (
  id bigint generated by default as identity primary key,
  slug varchar(120) not null unique,
  title varchar(190) not null,
  status text not null default 'ongoing' check (status in ('ongoing', 'ended')),
  period_label varchar(120) not null,
  venue varchar(190),
  partner varchar(190),
  summary varchar(500),
  image_url varchar(500),
  content text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table banners (
