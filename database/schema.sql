  title varchar(190) not null,
  program_type text not null check (program_type in ('experience', 'lecture', 'tour')),
  base_price integer not null check (base_price >= 0),
  duration varchar(80),
  is_visible smallint not null default 1,
  created_at timestamptz not null default now()
);

create table package_options (
  id bigint generated by default as identity primary key,
  code varchar(80) not null unique,
  title varchar(190) not null,
  description varchar(300),
  price integer not null default 0 check (price >= 0),
  price_type text not null default 'person' check (price_type in ('person', 'flat')),
  category text check (category in ('lodging', 'meal', 'transport', 'extra')),
  is_visible smallint not null default 1,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
