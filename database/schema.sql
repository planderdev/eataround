create index idx_product_reviews_user on product_reviews (user_id);

-- updated_at 자동 갱신 (MySQL의 on update current_timestamp 대체)
create trigger trg_users_updated_at before update on users for each row execute function public.set_updated_at();
create trigger trg_products_updated_at before update on products for each row execute function public.set_updated_at();
create trigger trg_reservations_updated_at before update on reservations for each row execute function public.set_updated_at();
create trigger trg_events_updated_at before update on events for each row execute function public.set_updated_at();
create trigger trg_quote_requests_updated_at before update on quote_requests for each row execute function public.set_updated_at();
create trigger trg_journals_updated_at before update on journals for each row execute function public.set_updated_at();
create trigger trg_product_reviews_updated_at before update on product_reviews for each row execute function public.set_updated_at();

